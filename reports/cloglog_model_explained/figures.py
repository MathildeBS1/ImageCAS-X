def design(p):
    """9 x 7 matrix of covariate values for one person (columns as COLS)."""
    return np.column_stack([np.full(9, p["score2"]), p["loglen"], p["curv"], p["taper"],
                            p["lm"] * LM_ROWS, p["rlad"] * LAD_ROWS, p["rlcx"] * LCX_ROWS])


BVEC = np.array([BETA[c] for c in COLS])


def eta_of(p):
    return ALPHA + design(p) @ BVEC


def gh(n):
    x, w = np.polynomial.hermite.hermgauss(n)
    return x, w


def person_risk(eta, sigma, n=40):
    """P = 1 - E_b[exp(-e^b S)], b ~ N(0, sigma^2), Gauss-Hermite with n nodes."""
    x, w = gh(n)
    S = np.exp(eta).sum()
    return 1 - (w * np.exp(-np.exp(np.sqrt(2) * sigma * x) * S)).sum() / np.sqrt(np.pi)


def seg_marginal(eta, sigma, n=40):
    x, w = gh(n)
    return 1 - (w[None] * np.exp(-np.exp(np.sqrt(2) * sigma * x)[None] * np.exp(eta)[:, None])).sum(1) / np.sqrt(np.pi)


# ------------------------------------------------------------------ numbers.tex
NUM = {}


def put(name, value, fmt="{:.3f}"):
    name = name.replace("2", "two")
    if isinstance(value, float) and abs(value) < 1e-12:
        value = 0.0
    assert re.fullmatch(r"[A-Za-z]+", name), name
    NUM[name] = fmt.format(value) if not isinstance(value, str) else value


def write_numbers():
    lines = ["% generated by figures.py, do not edit"]
    lines += [f"\\newcommand{{\\n{k}}}{{{v}}}" for k, v in NUM.items()]
    (HERE / "numbers.tex").write_text("\n".join(lines) + "\n")


def save(fig, name):
    fig.savefig(FIG / f"{name}.pdf")
    plt.close(fig)


