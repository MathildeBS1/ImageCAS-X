def draw_tree(ax, values, vmax, fmt="{:.3f}", label_fmt=None):
    cm = cmap_p()
    x, y = zip(*TREE["LM"])
    ax.plot(x, y, color=GREY, lw=6, solid_capstyle="round")
    ax.text(0.3, 0.05, "LM", ha="center", va="bottom", fontsize=8, color=GREY)
    for s, v in zip(SEGS, values):
        (x0, y0), (x1, y1) = TREE[s]
        ax.plot([x0, x1], [y0, y1], color=cm(0.15 + 0.85 * v / vmax), lw=7, solid_capstyle="round")
        mx, my = (x0 + x1) / 2, (y0 + y1) / 2
        if s == "pLCx":
            ax.text(mx, my + 0.12, f"{s} " + fmt.format(v), fontsize=7.5, ha="center", va="bottom")
            continue
        dx = 0.18 if s[1:] != "RCA" else -0.18
        ax.text(mx + dx, my, f"{s}\n" + fmt.format(v), fontsize=7.5,
                ha="left" if dx > 0 else "right", va="center")
    ax.set_xlim(-2.0, 3.0)
    ax.set_ylim(-2.7, 0.4)
    ax.set_aspect("equal")
    ax.axis("off")


