    ax.set_title("Person A: chance that each segment develops plaque in 10 years")
    save(fig, "f01_tree_p")

    # tree diagram, three LAD segments
    p3 = pA[:3]
    put("pThreeNone", np.prod(1 - p3))
    put("pThreeAny", 1 - np.prod(1 - p3))
    fig, ax = plt.subplots(figsize=(7.2, 4.4))
    ax.axis("off")
    levels = [(0.0, [0.5])]
    xs = [0.05, 0.33, 0.61, 0.89]
    nodes = {(): (xs[0], 0.5, 1.0)}
    for k in range(3):
        new = {}
        for path, (x, y, pr) in nodes.items():
            spread = 0.25 / (2 ** k)
            for out, dy in ((1, spread), (0, -spread)):
                q = p3[k] if out else 1 - p3[k]
                nx, ny = xs[k + 1], y + dy
                ax.plot([x, nx], [y, ny], color=RED if out else BLUE, lw=1.2)
                ax.text((x + nx) / 2, (y + ny) / 2 + (0.012 if out else -0.03),
                        f"{q:.3f}", fontsize=7, ha="center", color=RED if out else BLUE)
                new[path + (out,)] = (nx, ny, pr * q)
        nodes = new
    for path, (x, y, pr) in nodes.items():
        lab = "".join("P" if o else "–" for o in path)
        col = BLUE if sum(path) == 0 else "black"
        ax.text(x + 0.015, y, f"{lab}   {pr:.4f}", fontsize=7.5, va="center", color=col,
                fontweight="bold" if sum(path) == 0 else "normal")
    for k, s in enumerate(SEGS[:3]):
        ax.text((xs[k] + xs[k + 1]) / 2, 0.98, s, ha="center", fontsize=9, fontweight="bold")
    ax.text(0.0, 0.0, f"red = plaque (P), blue = no plaque (–).  Only the path –––  has no plaque anywhere: "
            f"{np.prod(1 - p3):.4f}.  P(any plaque) = 1 − {np.prod(1 - p3):.4f} = {1 - np.prod(1 - p3):.4f}",
            fontsize=8)
    ax.set_xlim(0, 1.15)
    ax.set_ylim(-0.02, 1.02)
    save(fig, "f02_probtree")


