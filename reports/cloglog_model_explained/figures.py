def simulate(n, seed=7):
    rng = np.random.default_rng(seed)
    rows, ys, ids = [], [], []
    for i in range(n):
        p = dict(score2=rng.normal(), lm=rng.normal(), rlad=rng.normal(), rlcx=rng.normal(),
                 loglen=rng.normal(0, 0.2, 9), curv=rng.normal(size=9), taper=rng.normal(size=9))
        X = design(p)
        b = rng.normal(0, SIGMA)
        q = 1 - np.exp(-np.exp(ALPHA + X @ BVEC + b))
        ys.append((rng.random(9) < q).astype(float))
        rows.append(X)
        ids.append(np.full(9, i))
    X = np.vstack(rows)
    D = np.tile(np.eye(9), (n, 1))
    return np.hstack([D, X]), np.concatenate(ys), np.concatenate(ids)


def negll(theta, Z, y, nper, nodes=20):
    beta, ls = theta[:-1], theta[-1]
    x, w = gh(nodes)
    u = np.sqrt(2) * np.exp(ls) * x                        # b at the nodes
    eta = Z @ beta
    mu = np.exp(np.clip(eta[:, None] + u[None], -30, 30))   # rows x nodes hazards
    ll_row = np.where(y[:, None] > 0, np.log(-np.expm1(-mu) + 1e-300), -mu)
    ll_person = ll_row.reshape(nper, 9, -1).sum(1)          # persons x nodes
    a = ll_person + np.log(w / np.sqrt(np.pi))[None]
    m = a.max(1, keepdims=True)
    return -(m[:, 0] + np.log(np.exp(a - m).sum(1))).sum()


def fit(Z, y, nper, fixed=None, start=None):
    k = Z.shape[1]
    th0 = np.zeros(k + 1) if start is None else start.copy()
    if start is None:
        th0[:9] = -3.0
        th0[-1] = 0.0
    free = np.ones(k + 1, bool)
    if fixed is not None:
        for idx, v in fixed.items():
            free[idx] = False
            th0[idx] = v

    def f(t):
        th = th0.copy(); th[free] = t
        return negll(th, Z, y, nper)
    r = minimize(f, th0[free], method="L-BFGS-B")
    th = th0.copy(); th[free] = r.x
    return th, -r.fun


