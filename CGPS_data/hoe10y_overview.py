"""One-page overview of the HØ_10Y dataset (dtu-gpu-7:/data/kimbr/HØ_10Y/): what is in each folder,
how the files link to study_id, and the few counts that matter for the thesis. The full quality
check (HU sampling, contour geometry, visual vs Medis) is hoe10y_qc.py; this reuses its file
discovery and reads no voxels, so it runs in a minute or two.

    python CGPS_data/hoe10y_overview.py                    # writes OUT_DIR/overview.md
    python CGPS_data/hoe10y_overview.py --root ... --out ...

Run it from the repo root. Aggregate counts only, no study_id; check against the data agreement
before copying overview.md off the DTU machine.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from pathlib import Path

import pandas as pd

import hoe10y_qc as hq
from clean_baseline_count import read_at_bl

OUT_DIR = hq.OUT_DIR
TRUNKS = {"LAD": ("plad", "mlad", "dlad"), "CX": ("pcx", "mcx", "dcx"), "RCA": ("prca", "mrca", "drca")}


def folders(root, files):
    """Per folder (up to two levels deep): files, extensions, most common name pattern."""
    rows = defaultdict(lambda: {"files": 0, "ext": Counter(), "pattern": Counter()})
    for p in files:
        rel = p.relative_to(root)
        key = "/".join(rel.parts[:-1][:2]) or "."
        r = rows[key]
        r["files"] += 1
        r["ext"]["".join(p.suffixes[-2:]).lower() or "(none)"] += 1
        r["pattern"][hq.masked(p.name)] += 1
    return pd.DataFrame([{"folder": k, "files": v["files"],
                          "extensions": ", ".join(f"{e} {n}" for e, n in v["ext"].most_common(4)),
                          "typical name": v["pattern"].most_common(1)[0][0]} for k, v in sorted(rows.items())])


def example_headers(found):
    out = []
    if found["niftis"]:
        import nibabel as nib
        img = nib.load(str(found["niftis"][0]["path"]))
        z = tuple(round(float(v), 2) for v in img.header.get_zooms()[:3])
        out.append(f"- NIfTI: shape {img.shape}, spacing {z} mm, orientation {''.join(nib.aff2axcodes(img.affine))}, "
                   f"dtype {img.get_data_dtype()}")
    if found["trees"]:
        v = hq.cq.read_vtk_legacy(found["trees"][0]["path"].read_bytes())
        out.append(f"- Medis tree: {len(v['points'])} points, cells {list(v['cells'])}, "
                   f"point arrays {list(v['point_data'])}, field data {list(v['field_data'])}")
    for kind in ("centerline", "lumen", "outer"):
        p = next((f[kind] for f in found["contours"].values() if kind in f), None)
        if p:
            v = hq.cq.read_vtk_legacy(p.read_bytes())
            out.append(f"- contour `{kind}`: {len(v['points'])} points, cells "
                       f"{ {t: len(c) for t, c in v['cells'].items()} }")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=hq.ROOT)
    ap.add_argument("--out", default=OUT_DIR)
    args = ap.parse_args()
    root, out = Path(args.root), Path(args.out).expanduser()
    out.mkdir(parents=True, exist_ok=True)

    found = hq.discover(root)
    sheets = hq.load_sheets(root)
    rep = ["# HØ_10Y overview", "", f"Root `{root}`, {len(found['files']):,} files. "
           "Generated by `CGPS_data/hoe10y_overview.py`; the full check is `hoe10y_qc.py`.", ""]

    # ---- 1. folders
    rep += ["## 1. Folders", "", hq.md(folders(root, found["files"])), ""]

    # ---- 2. what the files are
    contour_pat = {(v, i) for v, i, _ in found["contours"]}
    rep += ["## 2. File kinds", "",
            *[f"- {v} spreadsheet `{hq.SHEETS[v]}`: {len(df)} rows x {df.shape[1]} columns" for v, df in sheets.items()],
            f"- NIfTI volumes: {len(found['niftis'])} {dict(Counter(x['visit'] for x in found['niftis']))}",
            f"- Medis centerline trees (BL): {len(found['trees'])}",
            f"- Medis contour segments: {len(found['contours'])} in {len(contour_pat)} patient-visits "
            f"(file kinds {dict(Counter(k for f in found['contours'].values() for k in f))})",
            f"- logs: {[p.name for p in found['logs']]}",
            f"- other files: {len(found['other'])}", "", "Example of each kind:", "", *example_headers(found), ""]

    # ---- 3. linkage by study_id
    ids = {v: set(df[hq.ID_COL].map(hq.norm_id).dropna()) for v, df in sheets.items() if hq.ID_COL in df}
    nifti = {v: {x["id"] for x in found["niftis"] if x["visit"] == v} for v in ("BL", "FU")}
    tree = {t["id"] for t in found["trees"]}
    cont = {i for v, i in contour_pat if v == "BL"}
    bl, fu = ids.get("BL", set()), ids.get("FU", set())
    both = bl & fu & nifti["BL"] & nifti["FU"]
    rows = [("BL spreadsheet", bl), ("FU spreadsheet", fu), ("BL + FU spreadsheet", bl & fu),
            ("BL NIfTI", nifti["BL"]), ("FU NIfTI", nifti["FU"]), ("Medis tree", tree), ("Medis contours", cont),
            ("BL + FU spreadsheet and BL + FU NIfTI", both), ("  ... with a Medis tree", both & tree)]
    if "BL" in sheets:
        b = sheets["BL"]
        clean = (hq.num(b["ct_cag_sis"]) == 0) & (hq.num(b["ct_cag_sss"]) == 0) & read_at_bl(b)
        clean_ids = set(b.loc[clean, hq.ID_COL].map(hq.norm_id).dropna())
        rows += [("clean baseline, read at BL", clean_ids), ("  ... with FU read and BL + FU NIfTI", clean_ids & both)]
    rep += ["## 3. Patients per data source (linked by `study_id`)", "",
            hq.md(pd.DataFrame([(k, len(v)) for k, v in rows], columns=["set", "patients"])), ""]

    # ---- 4. what Medis contoured
    if found["contours"]:
        seg = Counter(s for v, _, s in found["contours"] if v == "BL")
        trunk = {a: sum(seg[s] for s in ss) for a, ss in TRUNKS.items()}
        rep += ["## 4. Medis contours per segment (diseased segments only)", "",
                hq.md(pd.DataFrame(seg.most_common(), columns=["segment", "contoured"])), "",
                f"Trunk totals: {trunk}", ""]

    (out / "overview.md").write_text("\n".join(rep), encoding="utf-8")
    print(f"wrote {out / 'overview.md'}")


if __name__ == "__main__":
    main()
